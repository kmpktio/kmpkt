    junit5PluginVersion.set("1.2.3")
    targetClasses.set(listOf("io.kmpkt.aggregate.*"))
    // Generated by the Kotlin compiler for data classes. Mutants there say nothing about our tests.
    excludedMethods.set(listOf("equals", "hashCode", "toString", "copy", "copy\$default", "component*"))
    // org.slf4j: restores part of pitest's own default, which setting this property replaces -
    // nobody asserts that a log line was written, so those mutants can never be killed.
    // kotlin.jvm.internal: compiler-inserted null checks and intrinsics.
    // kotlin.ResultKt: throwOnFailure calls in coroutine state machines of suspend functions.
    avoidCallsTo.set(listOf("org.slf4j", "kotlin.jvm.internal", "kotlin.ResultKt"))
    threads.set(4)
    outputFormats.set(listOf("HTML", "XML"))
    timestampedReports.set(false)
    mutationThreshold.set(70)
}
